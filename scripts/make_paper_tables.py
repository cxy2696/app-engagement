#!/usr/bin/env python
"""Generate LaTeX tables from the benchmark artefacts (no hand-copied numbers)."""

from __future__ import annotations

import json
from pathlib import Path

from engagegraph.evaluation.bootstrap import bootstrap_ci
from engagegraph.evaluation.metrics import EvalResult


def esc(value: str) -> str:
    return value.replace("_", r"\_")


def main() -> int:
    summary = json.loads(Path("artifacts/runs/benchmark.json").read_text())
    results = {}
    for name, record in summary["models"].items():
        directory = Path(record["run_dir"]) / "evaluation"
        if directory.exists():
            results[name] = EvalResult.load(directory)
    if not results:
        raise SystemExit("no evaluation results found")
    ordered = sorted(results, key=lambda n: -results[n].metrics["ndcg@10"])
    best = ordered[0]
    stats = summary.get("dataset_stats", {})
    header_lines = [
        "% Auto-generated by scripts/make_paper_tables.py. Do not edit by hand.",
        rf"\newcommand{{\BestModel}}{{{esc(best)}}}",
        rf"\newcommand{{\BestNDCG}}{{{results[best].metrics['ndcg@10']:.4f}}}",
        rf"\newcommand{{\DatasetUsers}}{{{stats.get('n_users', 0):,}}}".replace(",", "{,}"),
        rf"\newcommand{{\DatasetItems}}{{{stats.get('n_items', 0):,}}}".replace(",", "{,}"),
        rf"\newcommand{{\TrainInteractions}}{{{stats.get('n_train_interactions', 0):,}}}".replace(
            ",", "{,}"
        ),
        rf"\newcommand{{\TestTargets}}{{{stats.get('n_test_interactions', 0):,}}}".replace(
            ",", "{,}"
        ),
        rf"\newcommand{{\EvalUsers}}{{{stats.get('eval_users', 0):,}}}".replace(",", "{,}"),
        rf"\newcommand{{\ColdUsers}}{{{stats.get('cold_start_test_users', stats.get('cold_start_february_users', 0)):,}}}".replace(
            ",", "{,}"
        ),
        "",
    ]
    Path("paper/metrics.tex").write_text("\n".join(header_lines), encoding="utf-8")
    lines = [
        "% Auto-generated by scripts/make_paper_tables.py. Do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Full-catalogue next-month adoption ranking on the January--February 2024 panel. "
        r"Metrics are macro-averaged over evaluation users; the interval is a paired user-level "
        r"bootstrap (1{,}000 resamples, 95\%). Coverage and novelty make popularity concentration visible.}",
        r"\label{tab:main}",
        r"\begin{tabular}{lcccccc}",
        r"\toprule",
        r"Model & NDCG@10 (95\% CI) & Recall@10 & MAP@10 & HitRate@10 & Coverage@10 & Novelty@10 \\",
        r"\midrule",
    ]
    for name in ordered:
        result = results[name]
        ci = bootstrap_ci(result.per_user["ndcg@10"], n_boot=1000, seed=42)
        lines.append(
            f"{esc(name)} & {result.metrics['ndcg@10']:.4f} [{ci.ci_low:.4f}, {ci.ci_high:.4f}] & "
            f"{result.metrics['recall@10']:.4f} & {result.metrics['map@10']:.4f} & "
            f"{result.metrics['hit_rate@10']:.4f} & {result.metrics['coverage@10']:.3f} & "
            f"{result.metrics['novelty@10']:.3f} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

    comparisons = summary.get("comparisons", [])
    if comparisons:
        lines += [
            r"\begin{table}[t]",
            r"\centering",
            r"\caption{Paired comparisons against the popularity baseline on NDCG@10. "
            r"Intervals are user-level paired bootstrap; $p_{\mathrm{Holm}}$ controls the family-wise "
            r"error rate across candidates.}",
            r"\label{tab:comparisons}",
            r"\begin{tabular}{lccc}",
            r"\toprule",
            r"Candidate & $\Delta$ NDCG@10 & 95\% CI & $p_{\mathrm{Holm}}$ \\",
            r"\midrule",
        ]
        for record in comparisons:
            lines.append(
                f"{esc(record['candidate'])} & {record['difference']:+.4f} & "
                f"[{record['ci_low']:+.4f}, {record['ci_high']:+.4f}] & "
                f"{record.get('p_holm', float('nan')):.4f} \\\\"
            )
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    Path("paper/tables.tex").write_text("\n".join(lines), encoding="utf-8")

    print(
        f"wrote paper/metrics.tex and paper/tables.tex ({len(results)} models, {len(comparisons)} comparisons)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
